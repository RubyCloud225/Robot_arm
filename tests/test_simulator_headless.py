
"""P0-006.09 — Headless simulator acceptance tests.

Prove that the complete Simulator lifecycle works without
a viewer, render window, graphics context or display server.

The tests exercise real MuJoCo physics, not a mocked engine.
"""

from __future__ import annotations

import os
import subprocess
import sys
import textwrap
from pathlib import Path

import mujoco
import numpy as np
import pytest

from robot_arm_sim.simulator import (
    Simulator,
    SimulatorLifecycleError,
    SimulatorState,
)


@pytest.fixture
def panda_path() -> Path:
    """Use the same reviewed Panda asset as existing tests."""
    source = os.environ.get("ROBOT_ARM_PANDA_XML")

    if not source:
        pytest.fail(
            "ROBOT_ARM_PANDA_XML is required "
            "for headless acceptance tests"
        )

    path = Path(source).expanduser().resolve()
    assert path.is_file()
    return path


@pytest.fixture
def forbid_renderer(monkeypatch):
    """Fail if Simulator attempts to construct a renderer.

    A rendering dependency would violate the headless
    lifecycle contract even if the display happens to
    be available on the developer's machine.
    """
    def forbidden(*args, **kwargs):
        raise AssertionError(
            "Headless simulation attempted rendering"
        )

    # MuJoCo's high-level renderer construction is never
    # required by load, reset or physics stepping.
    monkeypatch.setattr(
        mujoco,
        "Renderer",
        forbidden,
    )


def test_complete_lifecycle_without_renderer(
    panda_path,
    forbid_renderer,
):
    """Load, integrate, reset and close with rendering forbidden."""
    sim = Simulator(panda_path)

    assert sim.state is SimulatorState.NEW

    sim.load()

    try:
        assert sim.state is SimulatorState.LOADED

        model = sim.model
        data = sim.data

        # Exercise both public integration interfaces.
        sim.step(n_substeps=5)
        sim.step_controller_period(period=0.04)

        assert sim.physics_step_count == 25
        assert sim.controller_step_count == 1
        assert sim.simulation_time == pytest.approx(
            25 * float(model.opt.timestep)
        )

        # Reset must refresh derived physics without a
        # rendering or interactive viewer operation.
        sim.reset()

        assert sim.model is model
        assert sim.data is data
        assert sim.physics_step_count == 0
        assert sim.controller_step_count == 0

    finally:
        sim.close()

    assert sim.state is SimulatorState.CLOSED


def test_physics_evolves_without_rendering(
    panda_path,
    forbid_renderer,
):
    """Physics integration must work independently of graphics."""
    sim = Simulator(panda_path)
    sim.load()

    try:
        ball_id = sim.model.body("ball").id
        initial_height = float(sim.data.xpos[ball_id, 2])

        sim.step(n_substeps=20)

        final_height = float(sim.data.xpos[ball_id, 2])

        assert final_height < initial_height
        assert sim.physics_step_count == 20
        assert sim.simulation_time > 0.0

    finally:
        sim.close()


def test_derived_positions_available_without_renderer(
    panda_path,
    forbid_renderer,
):
    """Headless execution still computes body and site positions."""
    sim = Simulator(panda_path)
    sim.load()

    try:
        sim.reset()

        # These are ordinary MuJoCo derived-state arrays,
        # not values generated by the rendering pipeline.
        assert np.all(np.isfinite(sim.data.xpos))
        assert np.all(np.isfinite(sim.data.site_xpos))
        assert np.all(np.isfinite(sim.data.geom_xpos))

        assert sim.data.xpos.shape == (
            sim.model.nbody,
            3,
        )
        assert sim.data.site_xpos.shape == (
            sim.model.nsite,
            3,
        )

    finally:
        sim.close()


def test_contacts_available_without_rendering(
    panda_path,
    forbid_renderer,
):
    """Contact generation is a physics operation, not drawing."""
    sim = Simulator(panda_path)
    sim.load()

    try:
        # Permit the initially elevated ball to settle.
        sim.step(n_substeps=200)

        assert int(sim.data.ncon) >=0
        assert sim.data.ncon >= 0

        # Contact metadata, when contacts exist, can be
        # inspected without constructing any renderer.
        for contact in sim.data.contact:
            assert 0 <= contact.geom1 < sim.model.ngeom
            assert 0 <= contact.geom2 < sim.model.ngeom

    finally:
        sim.close()


def test_headless_reset_is_repeatable(
    panda_path,
    forbid_renderer,
):
    """Repeated reset/integration cycles need no graphics."""
    sim = Simulator(panda_path)
    sim.load()

    try:
        baseline = sim.data.qpos.copy()

        for _ in range(3):
            sim.step_controller_period(period=0.04)
            assert sim.controller_step_count == 1

            sim.reset()

            np.testing.assert_array_equal(
                sim.data.qpos,
                baseline,
            )
            assert sim.physics_step_count == 0
            assert sim.controller_step_count == 0

    finally:
        sim.close()


def test_headless_simulators_remain_independent(
    panda_path,
    forbid_renderer,
):
    """Multiple simulations never depend on a shared viewer."""
    first = Simulator(panda_path)
    second = Simulator(panda_path)

    first.load()
    try:
        second.load()
        try:
            assert first.model is not second.model
            assert first.data is not second.data

            first.step_controller_period(period=0.04)
            second.step(n_substeps=3)

            assert first.physics_step_count == 20
            assert first.controller_step_count == 1

            assert second.physics_step_count == 3
            assert second.controller_step_count == 0

        finally:
            second.close()
    finally:
        first.close()


def test_headless_lifecycle_guards_unchanged(panda_path):
    """Headless operation must retain lifecycle restrictions."""
    sim = Simulator(panda_path)

    with pytest.raises(SimulatorLifecycleError):
        sim.step()

    sim.load()
    sim.close()

    with pytest.raises(SimulatorLifecycleError):
        sim.step_controller_period(period=0.04)


def test_headless_execution_in_fresh_subprocess(panda_path):
    """Execute an entire lifecycle without display variables.

    Unlike an in-process pytest test, the child Python
    interpreter starts with a fresh module import state.

    This is an acceptance test of the public Simulator API.
    """
    script = textwrap.dedent(
        """
        import os
        from pathlib import Path

        import mujoco

        from robot_arm_sim.simulator import Simulator

        # These variables must be absent in the child.
        assert "DISPLAY" not in os.environ
        assert "WAYLAND_DISPLAY" not in os.environ

        def rendering_forbidden(*args, **kwargs):
            raise AssertionError(
                "Unexpected renderer construction"
            )

        # No high-level renderer is permitted.
        mujoco.Renderer = rendering_forbidden

        sim = Simulator(
            Path(os.environ["ROBOT_ARM_PANDA_XML"])
        )

        sim.load()
        try:
            model = sim.model
            data = sim.data

            sim.reset()
            sim.step(n_substeps=5)
            sim.step_controller_period(period=0.04)

            assert sim.physics_step_count == 25
            assert sim.controller_step_count == 1
            assert data.time > 0.0

            assert sim.model is model
            assert sim.data is data

            sim.reset()

            assert sim.physics_step_count == 0
            assert sim.controller_step_count == 0
        finally:
            sim.close()

        print("HEADLESS_SIMULATION_PASS")
        """
    )

    # Copy the existing test environment, removing the
    # display addresses rather than changing the host.
    child_env = os.environ.copy()
    child_env.pop("DISPLAY", None)
    child_env.pop("WAYLAND_DISPLAY", None)

    child_env["ROBOT_ARM_PANDA_XML"] = str(panda_path)

    result = subprocess.run(
        [sys.executable, "-c", script],
        env=child_env,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )

    assert result.returncode == 0, (
        f"Headless subprocess failed.\\n"
        f"stdout:\\n{result.stdout}\\n"
        f"stderr:\\n{result.stderr}"
    )

    assert "HEADLESS_SIMULATION_PASS" in result.stdout
